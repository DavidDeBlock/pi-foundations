def test_probe_monorepo_detects_frontend_package_json():
    """A monorepo with a ``frontend/package.json`` is detected as JS."""
    d = _make_dir()
    try:
        _write(d / "frontend" / "package.json", json.dumps({
            "dependencies": {"react": "*"}
        }))
        _write(d / "frontend" / "pnpm-lock.yaml", "")
        result = probe_repo(d)
        assert "javascript" in result.languages or "typescript" in result.languages
        assert result.package_manager == "pnpm"
        assert "react" in result.frameworks
    finally:
        _cleanup(d)


def test_probe_monorepo_ignores_node_modules():
    """A ``node_modules/package.json`` doesn't pollute the framework detection."""
    d = _make_dir()
    try:
        # Real package.json with no react
        _write(d / "package.json", json.dumps({
            "dependencies": {"express": "*"}
        }))
        # Nested node_modules with a transitive dep's package.json
        _write(d / "node_modules" / "react" / "package.json", json.dumps({
            "dependencies": {"some-other-thing": "*"}
        }))
        result = probe_repo(d)
        # react is NOT in our dependencies, so should not be detected
        assert "react" not in result.frameworks
        assert "express" in result.frameworks
    finally:
        _cleanup(d)


