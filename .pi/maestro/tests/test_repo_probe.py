#!/usr/bin/env python3
"""
Unit tests for ``lib/repo_probe.py`` — the mechanical repo detection
module backing the ``maestro onboard`` command.

Each test scaffolds a fake repo directory in a temp dir, runs
``probe_repo()`` against it, and asserts on the resulting
``ProbeResult``. We never mock the filesystem — the probe is
intentionally filesystem-aware, and a mocked probe would test
nothing useful.

Run with: ``python3 tests/test_repo_probe.py``
"""

from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

# Add lib to path so we can import the module under test without
# installing the package.
sys.path.insert(0, str(Path(__file__).parent.parent / "lib"))

from repo_probe import (  # noqa: E402
    LOCKFILE_PRECEDENCE,
    PACKAGE_MANAGER_FROM_LOCKFILE,
    ProbeResult,
    probe_repo,
)


# ─── Helpers ─────────────────────────────────────────────────────────────


def _make_dir(prefix: str = "maestro_probe_test_") -> Path:
    """Return a fresh empty temp directory."""
    return Path(tempfile.mkdtemp(prefix=prefix))


def _cleanup(d: Path) -> None:
    """Best-effort recursive cleanup of a temp dir."""
    try:
        shutil.rmtree(d, ignore_errors=True)
    except Exception:
        pass


def _write(path: Path, content: str = "") -> None:
    """Write ``content`` to ``path``, creating parents as needed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


# ─── Language detection ──────────────────────────────────────────────────


def test_probe_detects_python_repo():
    """A repo with ``*.py`` files and ``pyproject.toml`` is detected as Python."""
    d = _make_dir()
    try:
        _write(d / "pyproject.toml", "[project]\nname = 'foo'\n")
        _write(d / "main.py", "print('hi')\n")
        result = probe_repo(d)
        assert "python" in result.languages, f"expected 'python' in {result.languages}"
    finally:
        _cleanup(d)


