# ─── Result shape ───────────────────────────────────────────────────────


def test_probe_result_is_always_fully_populated():
    """An empty directory still returns a ProbeResult with sensible defaults.

    No crashes, no None fields, no partial state. The shape of the
    result is always the same — only the *contents* differ.
    """
    d = _make_dir()
    try:
        result = probe_repo(d)
        assert isinstance(result, ProbeResult)
        assert isinstance(result.path, str)
        assert result.languages == []
        assert result.frameworks == []
        assert result.package_manager == ""
        assert result.test_command == ""
        assert result.build_command == ""
        assert result.lint_command == ""
        assert result.is_git_repo is False
        assert result.git_remote == ""
    finally:
        _cleanup(d)


def test_probe_to_dict_is_json_serialisable():
    """``ProbeResult.to_dict()`` round-trips through ``json.dumps``."""
    import json
    d = _make_dir()
    try:
        _write(d / "package.json", '{"dependencies": {"react": "*"}}')
        result = probe_repo(d)
        serialised = json.dumps(result.to_dict())
        assert isinstance(serialised, str)
        assert "react" in serialised
    finally:
        _cleanup(d)


def test_probe_does_not_crash_on_malformed_package_json():
    """A broken ``package.json`` doesn't crash the probe — it just yields empty JS signals."""
    d = _make_dir()
    try:
        _write(d / "package.json", "this is { not valid json")
        # Should not raise
        result = probe_repo(d)
        assert result.package_manager in ("npm", ""), (
            "no valid package.json means no lockfile-derived PM"
        )
    finally:
        _cleanup(d)


# ─── Module-level invariants ────────────────────────────────────────────


def test_lockfile_precedence_covers_all_supported_pms():
    """Every entry in :data:`PACKAGE_MANAGER_FROM_LOCKFILE` has a precedence entry."""
    for lockfile in PACKAGE_MANAGER_FROM_LOCKFILE.keys():
        assert lockfile in LOCKFILE_PRECEDENCE, (
            f"lockfile {lockfile!r} missing from LOCKFILE_PRECEDENCE"
        )


# ─── Test runner ────────────────────────────────────────────────────────


if __name__ == "__main__":
    import traceback

    tests = [v for k, v in globals().items() if k.startswith("test_") and callable(v)]
    passed = 0
    failed = 0
    for test_fn in tests:
        try:
            test_fn()
            print(f"  ✓ {test_fn.__name__}")
            passed += 1
        except Exception as e:
            print(f"  ✗ {test_fn.__name__}: {type(e).__name__}: {e}")
            traceback.print_exc()
            failed += 1
    print(f"\n{passed} passed, {failed} failed ({len(tests)} total)")
    sys.exit(0 if failed == 0 else 1)
