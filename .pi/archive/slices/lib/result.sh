#!/usr/bin/env bash
# result.sh — Result file reading, writing, and validation.
#
# Usage: source lib/config.sh; source lib/result.sh

RESULT_FILE="${CFG_RESULT_FILE}"

# ─── Validate Result File Exists and is Valid JSON ──────────────────────────
validate_result() {
    if [ ! -f "$RESULT_FILE" ]; then
        log_warn "No result file written at: $RESULT_FILE"
        return 1
    fi

    # Validate it's parseable JSON with a 'status' field
    local status
    status=$(python3 -c "
import json, sys
try:
    with open('${RESULT_FILE}') as f:
        d = json.load(f)
    if 'status' not in d:
        print('ERROR: missing status field', file=sys.stderr)
        sys.exit(1)
    print(d['status'])
except (json.JSONDecodeError, IOError) as e:
    print(f'ERROR: invalid JSON - {e}', file=sys.stderr)
    sys.exit(1)
" 2>/dev/null) || return 1

    echo "$status"
}

# ─── Read Status from Result File ──────────────────────────────────────────
read_result_status() {
    validate_result
}

# ─── Read Issues/Critique Array from Result File ────────────────────────────
read_result_issues() {
    python3 -c "
import json, sys
try:
    with open('${RESULT_FILE}') as f:
        d = json.load(f)
    # Try both 'issues' and 'critique' keys
    items = d.get('issues', d.get('critique', []))
    for item in items:
        print(item)
except (json.JSONDecodeError, IOError):
    print('Could not parse result file')
" 2>/dev/null || echo "Could not parse issues from result file"
}

# ─── Read Verdict from Result File ──────────────────────────────────────────
read_result_verdict() {
    python3 -c "
import json, sys
try:
    with open('${RESULT_FILE}') as f:
        d = json.load(f)
    print(d.get('verdict', 'unknown'))
except (json.JSONDecodeError, IOError):
    print('unknown')
" 2>/dev/null || echo "unknown"
}

# ─── Write Default Rejection Result ────────────────────────────────────────
write_rejection() {
    local issue_num="$1"
    shift
    local issues=("$@")

    python3 -c "
import json, sys
result = {
    'status': 'rejected',
    'slice': ${issue_num},
    'issues': $(printf '%s\n' '${issues[*]}' | python3 -c "import sys,json; print(json.dumps([l.strip() for l in sys.stdin if l.strip()]))")
}
with open('${RESULT_FILE}', 'w') as f:
    json.dump(result, f)
" 2>/dev/null || echo "{\"status\":\"rejected\",\"slice\":${issue_num},\"issues\":[\"Failed to write result\"]}" > "$RESULT_FILE"
}

# ─── Build Builder Comment from Result ──────────────────────────────────────
build_builder_comment() {
    local issue_num="$1"

    python3 -c "
import json, sys

try:
    with open('${RESULT_FILE}') as f:
        result = json.load(f)
except (json.JSONDecodeError, IOError):
    print('## [BUILDER] Implementation Summary\n\n**Issue:** #${issue_num}\n**Status:** Unknown')
    sys.exit(0)

status = result.get('status', 'unknown')
slice_num = result.get('slice', ${issue_num})
issues = result.get('issues', [])

lines = []
lines.append(f'## [BUILDER] Implementation Summary')
lines.append('')
lines.append(f'**Issue:** #{slice_num}')
lines.append(f'**Status:** {\"Approved\" if status == \"approved\" else \"Self-Rejected\"}')

if issues:
    lines.append('')
    lines.append('### Self-Review Issues Found')
    lines.append('')
    for i, issue in enumerate(issues, 1):
        lines.append(f'{i}. {issue}')

print('\\n'.join(lines))
" 2>/dev/null || echo "## [BUILDER] Implementation Summary\n\n**Issue:** #${issue_num}\n**Status:** Unknown"
}

# ─── Build Reviewer Comment from Result ─────────────────────────────────────
build_reviewer_comment() {
    local issue_num="$1"

    python3 -c "
import json, sys

try:
    with open('${RESULT_FILE}') as f:
        result = json.load(f)
except (json.JSONDecodeError, IOError):
    print('## Reviewer Verdict ❌\n\n**Issue:** #${issue_num}\n**Verdict:** Unknown')
    sys.exit(0)

status = result.get('status', 'unknown')
slice_num = result.get('slice', ${issue_num})
verdict_val = result.get('verdict', 'unknown')
critique = result.get('critique', [])

icon = '\u2705' if status == 'approved' else '\u274c'
verdict_label = verdict_val.replace('-', ' ').title() if verdict_val else 'Unknown'

lines = []
lines.append(f'## Reviewer Verdict {icon}')
lines.append('')
lines.append(f'**Issue:** #{slice_num}')
lines.append(f'**Verdict:** {verdict_label}')

if critique:
    lines.append('')
    lines.append(f'### Issues Found ({len(critique)})')
    lines.append('')
    for i, item in enumerate(critique, 1):
        lines.append(f'{i}. {item}')
elif status == 'approved':
    lines.append('')
    lines.append('All acceptance criteria met. Implementation is ready for manual verification.')

lines.append('')
lines.append('---')
lines.append('*This comment was auto-generated by the slice orchestrator.*')

print('\\n'.join(lines))
" 2>/dev/null || echo "## Reviewer Verdict ❌\n\n**Issue:** #${issue_num}\n**Verdict:** Unknown"
}
